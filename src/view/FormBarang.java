    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
if (txtKode.getText().trim().isEmpty() || txtNama.getText().trim().isEmpty() || txtStok.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Kode, Nama, dan Stok tidak boleh kosong!", "Peringatan", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int stok;
    try {
        stok = Integer.parseInt(txtStok.getText().trim());
        if (stok < 0) {
            JOptionPane.showMessageDialog(this, "Stok harus berupa angka >= 0!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Stok harus diisi dengan angka yang valid!", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    model.Barang b = new model.Barang(txtKode.getText(), txtNama.getText(), cmbKategori.getSelectedItem().toString(), stok);
    
    if (dao.insertData(b)) {
        JOptionPane.showMessageDialog(this, "Data berhasil disimpan!");
        loadTable();
        bersihkanForm();
    } else {
        JOptionPane.showMessageDialog(this, "Gagal menyimpan data (Kemungkinan Kode Barang sudah ada).", "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
if (txtKode.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Pilih data pada tabel terlebih dahulu!", "Peringatan", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int stok = Integer.parseInt(txtStok.getText().trim());
    model.Barang b = new model.Barang(txtKode.getText(), txtNama.getText(), cmbKategori.getSelectedItem().toString(), stok);

    if (dao.updateData(b)) {
        JOptionPane.showMessageDialog(this, "Data berhasil diubah!");
        loadTable();
        bersihkanForm();
    } else {
        JOptionPane.showMessageDialog(this, "Gagal mengubah data.", "Error", JOptionPane.ERROR_MESSAGE);
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
if (txtKode.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Pilih data yang akan dihapus dari tabel!", "Peringatan", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(this, "Apakah Anda yakin ingin menghapus data dengan kode: " + txtKode.getText() + "?", "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION);
    
    if (confirm == JOptionPane.YES_OPTION) {
        if (dao.deleteData(txtKode.getText())) {
            JOptionPane.showMessageDialog(this, "Data berhasil dihapus!");
            loadTable();
            bersihkanForm();
        } else {
            JOptionPane.showMessageDialog(this, "Gagal menghapus data.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnHapusActionPerformed

